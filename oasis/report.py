"""
Generation of the Markdown report in oasis/results/<case>-<label>.md.
"""

import os
from datetime import datetime

ACTUAL_PATH = os.path.dirname(os.path.abspath(__file__))


def write_report(case_dir, label, data):
    """Write a Markdown report with the results of the analysis. Based on the data returned by analyze()."""
    case, subject, assertion, inputs, original, violating, mutants, good = data
    params = [p["name"] for p in case["params"]]
    survived = [m for m in mutants if m[2] == "SURVIVED"]
    L = [
        f"# OASIs report: {case['method']} ({label})",
        "",
        f"- Date: {datetime.now():%Y-%m-%d %H:%M}",
        f"- Model: `{os.environ['OASIS_MODEL']}`",
        f"- Assertion: `{assertion}`",
        "",
        "## Program",
        "",
        "```java",
        subject.strip(),
        "```",
        "",
        "## 1. False positive check (is the assertion too strong?)",
        "",
        f"Inputs generated by the LLM: {len(inputs)}. ",
        f"Inputs that violate the assertion on the original program: **{len(violating)}**.",
        "",
        "| # | input | result | assertion |",
        "|---|---|---|---|",
    ]
    for i, inp in enumerate(inputs):
        v, res = original.get(i, ("?", "?"))
        res = res if len(res) <= 60 else res[:60] + "..."
        L.append(
            f"| {i} | `{', '.join(f'{n} = {x}' for n, x in zip(params, inp))}` | `{res}` | {v} |"
        )
    if violating:
        L += [
            "",
            "Counterexample tests (the program is correct, so the assertion is too strong):",
            "",
            "```java",
        ]
        for inp, res in violating:
            args = ", ".join(inp)
            L.append(f"// {case['method']}({args}) returns {res} -> assertion is false")
        L.append("```")
    L += [
        "",
        "## 2. False negative check (is the assertion too weak?)",
        "",
        f"Mutants are run on the {len(good)} inputs where the assertion holds on the original program. ",
        f"Mutants generated by the LLM: {len(mutants)}. Surviving (not killed and ",
        f"behaving differently from the original): **{len(survived)}**.",
        "",
        "| # | mutant | status |",
        "|---|---|---|",
    ]
    for i, (desc, _, status, _) in enumerate(mutants):
        L.append(f"| {i + 1} | {desc} | {status} |")
    for i, (desc, code, status, out) in enumerate(mutants):
        if status != "SURVIVED":
            continue
        diff = [
            (inputs[k], original[k][1], out[k][1])
            for k in good
            if out[k][1] != original[k][1]
        ]
        inp, exp, got = diff[0]
        L += [
            "",
            f"### Surviving mutant {i + 1}: {desc}",
            "",
            "```java",
            code,
            "```",
            "",
            f"Example: input `{', '.join(inp)}` -> original `{exp}`, mutant `{got}`, ",
            "and the assertion still holds.",
        ]
    L += ["", "## Feedback for the user", ""]
    L.append(
        "- The assertion looks **too strong**: refine it so that the counterexamples above are accepted."
        if violating
        else "- No false positives found: no evidence that the assertion is too strong."
    )
    L.append(
        "- The assertion looks **too weak**: refine it so that the surviving mutants above are killed."
        if survived
        else "- No surviving mutants: no evidence that the assertion is too weak."
    )
    path = os.path.join(
        ACTUAL_PATH, "results", f"{os.path.basename(case_dir.rstrip('/'))}-{label}.md"
    )
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")
    return path, len(violating), len(survived)
